/**
 * Builds docs/proofs/README.md from the proof JSON files written by the experiment scripts.
 * Usage: pnpm proofs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { ROOT } from "./lib/config.js";

type Step = { step: string; layer: string; signature: string; url: string; ms?: number };
type Proof = Record<string, unknown> & { steps: Step[] };

const dir = resolve(ROOT, "docs/proofs");
const titles: Record<string, string> = {
  "er-spike": "Phase 1: Ephemeral Rollup round trip",
  "lab-vrf-er": "Phase 2A: VRF on the public ER",
  "lab-vrf-tee": "Phase 2A: VRF on the TEE",
  "lab-per-tee": "Phase 2B: private permissions on the TEE",
  "lab-pick-tee": "Phase 2C: VRF picks the reader and rewrites the permission",
  "lab-crank-er": "Phase 2D: cranks on the public ER",
  "lab-crank-tee": "Phase 2D: cranks on the TEE",
};

const order = (name: string) => {
  const known = Object.keys(titles).indexOf(name);
  return known >= 0 ? known : 100 + name.length;
};

const files = readdirSync(dir)
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.replace(/\.json$/, ""))
  .sort((a, b) => order(a) - order(b) || a.localeCompare(b));

const short = (value: unknown) => {
  const text = typeof value === "string" ? value : JSON.stringify(value);
  return text.length > 220 ? `${text.slice(0, 217)}...` : text;
};

const sections = files.map((name) => {
  const proof = JSON.parse(readFileSync(resolve(dir, `${name}.json`), "utf8")) as Proof;
  const facts = { ...((proof.facts as Record<string, unknown>) ?? {}) };
  for (const [key, value] of Object.entries(proof)) {
    if (!["steps", "facts", "experiment", "network"].includes(key)) facts[key] = value;
  }
  const title = titles[name] ?? `Phase 2E: ${name.replace("lab-slots-", "multi-account sweep, ")}`;
  const factLines = Object.entries(facts).map(
    ([key, value]) => `- **${key}:** \`${short(value)}\``,
  );
  const rows = proof.steps.map(
    (s) => `| ${s.step} | ${s.layer} | ${s.ms ?? ""} | [${s.signature.slice(0, 8)}...](${s.url}) |`,
  );
  return [
    `## ${title}`,
    "",
    `Raw data: [${name}.json](${name}.json)`,
    "",
    ...factLines,
    "",
    "| Step | Layer | Confirm (ms) | Transaction |",
    "|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
});

const intro = `# Onchain proofs (devnet)

Generated by \`pnpm proofs\` from the experiment scripts in \`scripts/src\`. Every row links to a real
devnet transaction. Rollup and TEE transactions use the Solana Explorer custom-cluster link; if a
view is empty, query the endpoint named in the facts directly. Confirm times include network round
trips from the client, not rollup execution time.

Findings and design consequences: [../phase-2-findings.md](../phase-2-findings.md).

`;

writeFileSync(resolve(dir, "README.md"), intro + sections.join("\n"));
console.log(`wrote docs/proofs/README.md (${files.length} experiments)`);
